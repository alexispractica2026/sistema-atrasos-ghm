-- 1. Tabla de Atrasos (Ingresos)
CREATE TABLE IF NOT EXISTS public.atrasos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL DEFAULT CURRENT_DATE,
    hora TIME NOT NULL DEFAULT CURRENT_TIME,
    nombre TEXT NOT NULL,
    nombre_normalizado TEXT NOT NULL,
    curso TEXT NOT NULL,
    motivo TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Tabla de Retiros (Salidas Anticipadas)
CREATE TABLE IF NOT EXISTS public.retiros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL DEFAULT CURRENT_DATE,
    hora TIME NOT NULL DEFAULT CURRENT_TIME,
    nombre TEXT NOT NULL,
    nombre_normalizado TEXT NOT NULL,
    curso TEXT NOT NULL,
    quien_retira TEXT NOT NULL,
    parentesco TEXT NOT NULL,
    motivo TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Índices para acelerar búsquedas y conteo de atrasos
CREATE INDEX IF NOT EXISTS idx_atrasos_nombre_norm ON public.atrasos (nombre_normalizado);
CREATE INDEX IF NOT EXISTS idx_atrasos_fecha ON public.atrasos (fecha DESC);
CREATE INDEX IF NOT EXISTS idx_retiros_fecha ON public.retiros (fecha DESC);

-- ============================================================================
-- POLÍTICAS DE SEGURIDAD (RLS)
-- Nota: Para uso interno rápido con la clave anon de Supabase, habilitamos
-- lectura/escritura. Si luego agregas Login con Supabase Auth, puedes
-- restringir estas políticas a 'authenticated'.
-- ============================================================================
ALTER TABLE public.atrasos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.retiros ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Permitir lectura atrasos" ON public.atrasos
    FOR SELECT USING (true);

CREATE POLICY "Permitir insercion atrasos" ON public.atrasos
    FOR INSERT WITH CHECK (true);

CREATE POLICY "Permitir eliminacion atrasos" ON public.atrasos
    FOR DELETE USING (true);

CREATE POLICY "Permitir lectura retiros" ON public.retiros
    FOR SELECT USING (true);

CREATE POLICY "Permitir insercion retiros" ON public.retiros
    FOR INSERT WITH CHECK (true);

CREATE POLICY "Permitir eliminacion retiros" ON public.retiros
    FOR DELETE USING (true);
