-- ============================================================================
-- ESQUEMA DE BASE DE DATOS V2 PARA SUPABASE (CON ESTUDIANTES Y RUT)
-- Sistema de Gestión Escolar - Colegio García Hurtado de Mendoza
-- ============================================================================

-- 1. Tabla de Estudiantes (Catálogo oficial)
CREATE TABLE IF NOT EXISTS public.estudiantes (
    rut TEXT PRIMARY KEY,
    nombre TEXT NOT NULL,
    curso TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Actualizar o crear Tabla de Atrasos
CREATE TABLE IF NOT EXISTS public.atrasos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rut TEXT,
    fecha DATE NOT NULL DEFAULT CURRENT_DATE,
    hora TIME NOT NULL DEFAULT CURRENT_TIME,
    nombre TEXT NOT NULL,
    nombre_normalizado TEXT NOT NULL,
    curso TEXT NOT NULL,
    motivo TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Si ya existía la tabla atrasos de la v1, agregamos la columna rut sin borrar datos:
ALTER TABLE public.atrasos ADD COLUMN IF NOT EXISTS rut TEXT;

-- 3. Actualizar o crear Tabla de Retiros
CREATE TABLE IF NOT EXISTS public.retiros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rut TEXT,
    fecha DATE NOT NULL DEFAULT CURRENT_DATE,
    hora TIME NOT NULL DEFAULT CURRENT_TIME,
    nombre TEXT NOT NULL,
    nombre_normalizado TEXT NOT NULL,
    curso TEXT NOT NULL,
    quien_retira TEXT NOT NULL,
    parentesco TEXT NOT NULL,
    motivo TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Si ya existía la tabla retiros de la v1, agregamos la columna rut sin borrar datos:
ALTER TABLE public.retiros ADD COLUMN IF NOT EXISTS rut TEXT;

-- Índices para búsquedas rápidas
CREATE INDEX IF NOT EXISTS idx_atrasos_rut ON public.atrasos (rut);
CREATE INDEX IF NOT EXISTS idx_atrasos_nombre_norm ON public.atrasos (nombre_normalizado);
CREATE INDEX IF NOT EXISTS idx_atrasos_fecha ON public.atrasos (fecha DESC);
CREATE INDEX IF NOT EXISTS idx_retiros_rut ON public.retiros (rut);
CREATE INDEX IF NOT EXISTS idx_retiros_fecha ON public.retiros (fecha DESC);

-- ============================================================================
-- POLÍTICAS DE SEGURIDAD (RLS)
-- ============================================================================
ALTER TABLE public.estudiantes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.atrasos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.retiros ENABLE ROW LEVEL SECURITY;

-- Políticas para estudiantes
DROP POLICY IF EXISTS "Acceso total estudiantes" ON public.estudiantes;
CREATE POLICY "Acceso total estudiantes" ON public.estudiantes
    FOR ALL USING (true) WITH CHECK (true);

-- Políticas para atrasos
DROP POLICY IF EXISTS "Permitir lectura atrasos" ON public.atrasos;
DROP POLICY IF EXISTS "Permitir insercion atrasos" ON public.atrasos;
DROP POLICY IF EXISTS "Permitir eliminacion atrasos" ON public.atrasos;
CREATE POLICY "Acceso total atrasos" ON public.atrasos
    FOR ALL USING (true) WITH CHECK (true);

-- Políticas para retiros
DROP POLICY IF EXISTS "Permitir lectura retiros" ON public.retiros;
DROP POLICY IF EXISTS "Permitir insercion retiros" ON public.retiros;
DROP POLICY IF EXISTS "Permitir eliminacion retiros" ON public.retiros;
CREATE POLICY "Acceso total retiros" ON public.retiros
    FOR ALL USING (true) WITH CHECK (true);
